import crypto from 'crypto';
import { headers } from 'next/headers';
import { createAdminClient } from '@nusc/db';

export async function POST(req: Request) {
    const rawBody = await req.text();
    const headersList = await headers();
    const signature = headersList.get('x-razorpay-signature');
    const secret = process.env.RAZORPAY_WEBHOOK_SECRET || 'dummy_webhook_secret';

    if (!signature) {
        return new Response('Missing signature', { status: 400 });
    }

    // 1. Generate expected signature
    const expectedSignature = crypto
        .createHmac('sha256', secret)
        .update(rawBody)
        .digest('hex');

    const expectedBuffer = Buffer.from(expectedSignature);
    const signatureBuffer = Buffer.from(signature);

    // Guard against length mismatch to prevent timingSafeEqual RangeError
    if (expectedBuffer.length !== signatureBuffer.length) {
        return new Response('Invalid signature', { status: 400 });
    }

    // 2. Constant-time comparison to prevent timing attacks
    const isValid = crypto.timingSafeEqual(expectedBuffer, signatureBuffer);
    if (!isValid) {
        return new Response('Invalid signature', { status: 400 });
    }

    let event: any;
    try {
        event = JSON.parse(rawBody);
    } catch {
        return new Response('Invalid JSON payload', { status: 400 });
    }

    // 3. Safe idempotent processing
    if (event.event === 'payment.captured') {
        const payment = event.payload?.payment?.entity;
        if (!payment) {
            return new Response('Missing payment entity', { status: 400 });
        }

        // Strict payment entity validations
        const paymentId = payment.id;
        const orderId = payment.order_id;
        const amount = payment.amount;
        const currency = payment.currency;
        const { userId, type } = payment.notes || {};

        // 3a. Validate payment ID format
        if (!paymentId || typeof paymentId !== 'string' || !paymentId.startsWith('pay_')) {
            return new Response('Invalid payment ID format', { status: 400 });
        }

        // 3b. Validate order ID format
        if (!orderId || typeof orderId !== 'string' || !orderId.startsWith('order_')) {
            return new Response('Invalid order ID format', { status: 400 });
        }

        // 3c. Validate amount (₹10 = 1000 paise)
        if (amount !== 1000) {
            return new Response(`Invalid payment amount: expected 1000 paise, got ${amount}`, { status: 400 });
        }

        // 3d. Validate currency
        if (currency !== 'INR') {
            return new Response(`Invalid payment currency: expected INR, got ${currency}`, { status: 400 });
        }

        // 3e. Validate registration fee context and member binding
        if (type !== 'registration_fee' || !userId) {
            return new Response('Irrelevant or unbound payment notes', { status: 400 });
        }

        const adminSupabase = createAdminClient();

        // 3f. Authoritative Order Lookup: verify order ID was generated by our backend for this member
        const { data: member, error: memberFetchError } = await adminSupabase
            .from('members')
            .select('id, user_id, status, registration_payment_status, registration_payment_id, registration_order_id')
            .eq('registration_order_id', orderId)
            .single();

        if (memberFetchError || !member) {
            console.error('Order not found or not associated with any member:', orderId, memberFetchError);
            return new Response('Order not found or not associated with any member', { status: 404 });
        }

        // 3g. Verify member ownership: payment notes userId must strictly match the registered member for this order
        if (userId && member.user_id !== userId) {
            console.error(`Order-to-member mismatch: order ${orderId} belongs to user ${member.user_id}, but notes indicated user ${userId}`);
            return new Response('Order-to-member mismatch: payment notes do not match registered member', { status: 403 });
        }

        // 3h. Anti-theft / Cross-member check: Ensure paymentId has not been used by ANY OTHER member
        const { data: existingPaymentMember } = await adminSupabase
            .from('members')
            .select('id')
            .eq('registration_payment_id', paymentId)
            .neq('id', member.id)
            .maybeSingle();

        if (existingPaymentMember) {
            console.error('Payment ID already used for another member:', paymentId, existingPaymentMember.id);
            return new Response('Payment ID already associated with another registration', { status: 409 });
        }

        // 3i. Idempotency check: if already paid
        if (member.registration_payment_status === 'paid') {
            if (member.registration_payment_id === paymentId) {
                // Exact duplicate webhook delivery for the already processed payment
                return new Response(JSON.stringify({ 
                    status: 'already_processed', 
                    member_id: member.id,
                    reason: 'duplicate_webhook'
                }), {
                    status: 200,
                    headers: { 'Content-Type': 'application/json' },
                });
            } else {
                // Distinct second captured payment for the same registration (duplicate financial charge)
                console.warn(`[RECONCILIATION NEEDED] Duplicate financial charge detected for member ${member.id}: existing ${member.registration_payment_id}, duplicate ${paymentId}`);

                // Persist durable, actionable reconciliation record for operations/finance review
                let reconId: string | null = null;
                try {
                    const { data: reconRecord, error: reconError } = await adminSupabase
                        .from('payment_reconciliations')
                        .insert({
                            member_id: member.id,
                            order_id: orderId,
                            existing_payment_id: member.registration_payment_id,
                            duplicate_payment_id: paymentId,
                            amount: amount,
                            currency: currency,
                            reason: 'duplicate_financial_charge',
                            status: 'requires_manual_refund',
                            metadata: {
                                userId: userId,
                                event: event.event,
                                detected_at: new Date().toISOString(),
                            }
                        })
                        .select('id')
                        .single();

                    if (reconError) {
                        console.error('[RECONCILIATION PERSISTENCE FAILED]', reconError);
                    } else if (reconRecord) {
                        reconId = reconRecord.id;
                    }
                } catch (e) {
                    console.error('[RECONCILIATION PERSISTENCE EXCEPTION]', e);
                }

                return new Response(JSON.stringify({ 
                    status: 'already_processed', 
                    member_id: member.id,
                    reason: 'duplicate_financial_charge',
                    existing_payment_id: member.registration_payment_id,
                    duplicate_payment_id: paymentId,
                    reconciliation_id: reconId,
                    reconciliation_logged: true
                }), {
                    status: 200,
                    headers: { 'Content-Type': 'application/json' },
                });
            }
        }

        // 3j. Atomic update only if registration_payment_status is pending
        const { error: updateError } = await adminSupabase
            .from('members')
            .update({
                status: 'active',
                registration_payment_status: 'paid',
                registration_payment_id: paymentId,
            })
            .eq('id', member.id)
            .eq('registration_payment_status', 'pending');

        if (updateError) {
            console.error('Failed to update member payment status:', updateError);
            return new Response('Database error', { status: 500 });
        }

        return new Response(JSON.stringify({ status: 'activated', member_id: member.id }), {
            status: 200,
            headers: { 'Content-Type': 'application/json' },
        });
    }

    if (event.event === 'payment.failed') {
        const payment = event.payload?.payment?.entity;
        const orderId = payment?.order_id;

        if (orderId) {
            const adminSupabase = createAdminClient();
            // Verify member: never downgrade or disrupt if already active/paid!
            const { data: member } = await adminSupabase
                .from('members')
                .select('status, registration_payment_status')
                .eq('registration_order_id', orderId)
                .single();

            if (member && member.registration_payment_status === 'paid') {
                // Ignore failure event if user already has paid status
                return new Response(JSON.stringify({ status: 'ignored_already_paid' }), {
                    status: 200,
                    headers: { 'Content-Type': 'application/json' },
                });
            }
        }

        return new Response(JSON.stringify({ status: 'failed_acknowledged' }), {
            status: 200,
            headers: { 'Content-Type': 'application/json' },
        });
    }

    return new Response('OK', { status: 200 });
}

